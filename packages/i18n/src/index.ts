export function formatStatusLabel(status: string, locale: SupportedLocale): string {
  return statusLabels[locale][status] ?? unknownStatusLabels[locale];
}

export function direction(locale: SupportedLocale): 'rtl' | 'ltr' {
  return locale === 'ar' || locale === 'ur' ? 'rtl' : 'ltr';
}
export type TranslationVariables = Readonly<Record<string, string | number>>;
export function translate(
  locale: SupportedLocale,
  key: TranslationKey,
  variables: TranslationVariables = {},
): string {
  return resources[locale].translation[key].replace(
    /\{\{([A-Za-z][A-Za-z0-9_]*)\}\}/g,
    (token, name: string) => {
      const value = variables[name];
      return value === undefined ? token : String(value);
    },
  );
}
export async function createI18n(locale: SupportedLocale): Promise<i18n> {
  const instance = i18next.createInstance();
  await instance.init({
    lng: locale,
    fallbackLng: 'ar',
    resources,
    interpolation: { escapeValue: true },
    returnNull: false,
  });
  return instance;
}
export function formatSar(amountMinor: number, locale: SupportedLocale): string {
  return new Intl.NumberFormat(locale === 'ar' ? 'ar-SA' : locale, {
    style: 'currency',
    currency: 'SAR',
  }).format(amountMinor / 100);
}
